use crate::memory::db::MemoryDb;
use anyhow::{Context, Result};
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::{SystemTime, UNIX_EPOCH};
use tracing::{info, warn};

pub const DEBOUNCE_WINDOW_MS: u64 = 500;

/// Resolves the default path for `profile.md` under `~/.jarvis/memory/profile.md`.
pub fn get_default_profile_path() -> PathBuf {
    let home = std::env::var("USERPROFILE")
        .or_else(|_| std::env::var("HOME"))
        .unwrap_or_else(|_| ".".into());

    PathBuf::from(home)
        .join(".jarvis")
        .join("memory")
        .join("profile.md")
}

fn current_time_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis() as u64
}

#[derive(Clone)]
pub struct ProfileSyncManager {
    db: MemoryDb,
    profile_path: PathBuf,
    last_sync_timestamp_ms: Arc<AtomicU64>,
}

impl ProfileSyncManager {
    pub fn new(db: MemoryDb, profile_path: Option<PathBuf>) -> Self {
        let path = profile_path.unwrap_or_else(get_default_profile_path);
        Self {
            db,
            profile_path: path,
            last_sync_timestamp_ms: Arc::new(AtomicU64::new(0)),
        }
    }

    pub fn profile_path(&self) -> &Path {
        &self.profile_path
    }

    /// Atomically exports all facts from the SQLite database to `profile.md`
    /// via a temporary file write (`.tmp`) followed by atomic rename.
    pub async fn export_profile_atomic(&self) -> Result<()> {
        if let Some(parent) = self.profile_path.parent() {
            fs::create_dir_all(parent).ok();
        }

        let facts = self.db.list_facts().await?;

        let mut output = String::new();
        output.push_str("# Jarvis User Profile\n");
        output.push_str("<!-- Auto-generated by Better Jarvis. Manual edits synchronize to memory. -->\n\n");

        let mut current_tier = String::new();
        for fact in facts {
            if fact.tier != current_tier {
                current_tier = fact.tier.clone();
                output.push_str(&format!("## {}\n", capitalize(&current_tier)));
            }
            output.push_str(&format!("- **{}**: {}\n", fact.key, fact.value));
        }

        let tmp_path = self.profile_path.with_extension("md.tmp");

        fs::write(&tmp_path, output.as_bytes())
            .with_context(|| format!("Failed to write temporary profile to {:?}", tmp_path))?;

        // Update timestamp prior to rename so file watcher ignores this event
        self.last_sync_timestamp_ms
            .store(current_time_ms(), Ordering::SeqCst);

        fs::rename(&tmp_path, &self.profile_path)
            .with_context(|| format!("Failed to rename {:?} to {:?}", tmp_path, self.profile_path))?;

        info!("Atomically mirrored profile memory to {:?}", self.profile_path);
        Ok(())
    }

    /// Imports facts from `profile.md` into the SQLite database.
    /// Ignores sync events that occur within the 500 ms debounce window to avoid infinite loops.
    pub async fn import_profile_if_external(&self) -> Result<bool> {
        let now = current_time_ms();
        let last_sync = self.last_sync_timestamp_ms.load(Ordering::SeqCst);

        if now.saturating_sub(last_sync) < DEBOUNCE_WINDOW_MS {
            // Self-triggered event within debounce window; safely ignore
            return Ok(false);
        }

        if !self.profile_path.exists() {
            return Ok(false);
        }

        let content = match fs::read_to_string(&self.profile_path) {
            Ok(c) => c,
            Err(e) => {
                warn!("Could not read {:?}: {}", self.profile_path, e);
                return Ok(false);
            }
        };

        let mut current_tier = "preference".to_string();
        let mut count = 0;

        for line in content.lines() {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with("<!--") {
                continue;
            }

            if let Some(heading) = trimmed.strip_prefix("## ") {
                current_tier = heading.trim().to_lowercase();
                continue;
            }

            if let Some(item) = trimmed.strip_prefix("- ") {
                if let Some((k, v)) = parse_key_value(item) {
                    self.db.upsert_fact(&k, &v, &current_tier).await?;
                    count += 1;
                }
            }
        }

        self.last_sync_timestamp_ms
            .store(current_time_ms(), Ordering::SeqCst);

        info!("Imported {} facts from {:?} into SQLite", count, self.profile_path);
        Ok(true)
    }
}

fn capitalize(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
    }
}

fn parse_key_value(line: &str) -> Option<(String, String)> {
    let trimmed = line.trim();
    if let Some(stripped) = trimmed.strip_prefix("**") {
        if let Some(end_bold) = stripped.find("**:") {
            let key = stripped[..end_bold].trim();
            let val = stripped[end_bold + 3..].trim();
            return Some((key.to_string(), val.to_string()));
        }
    }

    if let Some((k, v)) = trimmed.split_once(':') {
        let key = k.trim().trim_matches('*');
        let val = v.trim();
        if !key.is_empty() {
            return Some((key.to_string(), val.to_string()));
        }
    }

    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_parse_key_value() {
        assert_eq!(
            parse_key_value("**browser**: chrome"),
            Some(("browser".into(), "chrome".into()))
        );
        assert_eq!(
            parse_key_value("volume: 80%"),
            Some(("volume".into(), "80%".into()))
        );
        assert_eq!(
            parse_key_value("**dark_mode**: enabled"),
            Some(("dark_mode".into(), "enabled".into()))
        );
    }

    #[tokio::test]
    async fn test_atomic_export_and_import() {
        let temp_dir = std::env::temp_dir().join(format!("jarvis_test_mem_{}", current_time_ms()));
        fs::create_dir_all(&temp_dir).unwrap();
        let profile_file = temp_dir.join("profile.md");

        let db = MemoryDb::in_memory().unwrap();
        db.upsert_fact("theme", "emerald_dark", "preferences").await.unwrap();
        db.upsert_fact("user", "Youssef", "profile").await.unwrap();

        let sync_mgr = ProfileSyncManager::new(db.clone(), Some(profile_file.clone()));
        sync_mgr.export_profile_atomic().await.unwrap();

        assert!(profile_file.exists());
        let text = fs::read_to_string(&profile_file).unwrap();
        assert!(text.contains("**theme**: emerald_dark"));
        assert!(text.contains("**user**: Youssef"));

        // Add a line manually and test import
        let modified = text + "\n- **editor**: neovim\n";
        fs::write(&profile_file, modified).unwrap();

        // Advance debounce window to simulate external user edit
        sync_mgr.last_sync_timestamp_ms.store(0, Ordering::SeqCst);

        let imported = sync_mgr.import_profile_if_external().await.unwrap();
        assert!(imported);
        assert_eq!(db.get_fact("editor").await.unwrap().unwrap(), "neovim");

        db.shutdown().await.unwrap();
        let _ = fs::remove_dir_all(temp_dir);
    }

    #[tokio::test]
    async fn test_debounce_suppresses_self_triggered_sync() {
        let temp_dir = std::env::temp_dir().join(format!("jarvis_test_debounce_{}", current_time_ms()));
        fs::create_dir_all(&temp_dir).unwrap();
        let profile_file = temp_dir.join("profile.md");

        let db = MemoryDb::in_memory().unwrap();
        let sync_mgr = ProfileSyncManager::new(db.clone(), Some(profile_file.clone()));

        // Simulate recent export
        sync_mgr.last_sync_timestamp_ms.store(current_time_ms(), Ordering::SeqCst);

        // Immediate import within 500 ms window must be ignored
        let result = sync_mgr.import_profile_if_external().await.unwrap();
        assert!(!result);

        db.shutdown().await.unwrap();
        let _ = fs::remove_dir_all(temp_dir);
    }
}
